func parse(t *testing.T, src string) []jiraItem {
	t.Helper()
	items, err := ParseJiraXML(strings.NewReader(src))
	if err != nil {
		t.Fatal(err)
	}
	return items
}

func TestImportJira(t *testing.T) {
	s := newTestStore(t)
	res, err := s.ImportJira([][]jiraItem{parse(t, exportA)})
	if err != nil {
		t.Fatal(err)
	}
	if res.IssuesCreated != 3 || res.Comments != 1 || res.Links != 1 {
		t.Fatalf("result: %+v", res)
	}
	if len(res.ProjectsCreated) != 1 || len(res.ReleasesCreated) != 2 || len(res.StatusesAdded) != 0 {
		t.Fatalf("result: %+v", res)
	}

	p, _ := s.Project("WAR")
	if p.Name != "Warman" || p.NextNumber != 13 {
		t.Fatalf("project: %+v", p)
	}
	i, _ := s.Issue("WAR-12")
	if i.Type != "Task" || i.Priority != "High" || statusName(&p, i.StatusID) != "TODO" {
		t.Fatalf("issue: %+v", i)
	}
	if i.Description != "First line\nsecond line with `code`" {
		t.Fatalf("description: %q", i.Description)
	}
	if i.Created.Format("2006-01-02 15:04") != "2026-10-20 20:01" {
		t.Fatalf("created: %v", i.Created)
	}
	if i.EpicID != 0 {
		t.Fatal("epic set although it isn't imported yet")
	}
	done, _ := s.Issue("WAR-11")
	if statusName(&p, done.StatusID) != "Done" || done.Resolved == nil || done.Resolved.Format("15:04") != "17:43" {
		t.Fatalf("done issue: %+v", done)
	}
	if testing, _ := s.Issue("WAR-10"); statusName(&p, testing.StatusID) != "Testing" {
		t.Fatal("TESTING should map to Testing")
	}
	if testing, _ := s.Issue("WAR-10"); i.Board || !done.Board || !testing.Board {
		t.Fatal("to-do issues go to the backlog, the others onto the board")
	}

	// Backlog order follows Jira's rank, not the key.
	is, _ := s.Issues("WAR", IssueFilter{})
	if is[0].Key != "WAR-10" || is[1].Key != "WAR-11" || is[2].Key != "WAR-12" {
		t.Fatalf("rank order: %s %s %s", is[0].Key, is[1].Key, is[2].Key)
	}

	links, _ := s.Links("WAR-12")
	if len(links) != 1 || links[0].Label != "is blocked by" || links[0].Key != "WAR-10" {
		t.Fatalf("links: %+v", links)
	}
	cs, _ := s.Comments("WAR-12")
	if len(cs) != 1 || cs[0].Body != "Looks **fine**" {
		t.Fatalf("comments: %+v", cs)
	}

	// The epic arrives with a second import: the pending parent resolves,
	// and the unknown status is added to the workflow before Done.
	res, err = s.ImportJira([][]jiraItem{parse(t, exportB)})
	if err != nil {
		t.Fatal(err)
	}
	if len(res.StatusesAdded) != 1 {
		t.Fatalf("statuses added: %+v", res)
	}
	epic, _ := s.Issue("WAR-3")
	i, _ = s.Issue("WAR-12")
	if i.EpicID != epic.ID {
		t.Fatal("pending epic link not resolved")
	}
	p, _ = s.Project("WAR")
	if p.Statuses[len(p.Statuses)-1].Name != "Done" || statusName(&p, epic.StatusID) != "Code Review" {
		t.Fatalf("workflow: %+v", p.Statuses)
	}

	// Importing the same file again updates instead of duplicating.
	s.UpdateIssue("WAR-12", IssueInput{Summary: ptr("changed here")})
	res, _ = s.ImportJira([][]jiraItem{parse(t, exportA)})
	if res.IssuesCreated != 0 || res.IssuesUpdated != 3 || res.Comments != 0 || res.Links != 0 {
		t.Fatalf("re-import: %+v", res)
	}
	i, _ = s.Issue("WAR-12")
	if i.Summary != "Make the thing" || i.EpicID != epic.ID {
		t.Fatalf("re-import: %+v", i)
	}
	if all, _ := s.Issues("WAR", IssueFilter{}); len(all) != 4 {
		t.Fatalf("issue count %d", len(all))
	}
	// New local issues continue after the highest imported number.
	n := mustIssue(t, s, "WAR", "new")
	if n.Key != "WAR-13" {
		t.Fatalf("next key %s", n.Key)
	}
}

func jiraItemXML(key, project, status, category string) string {
	return `<item><key>` + key + `</key><project key="` + project + `">` + project + `</project>
  <summary>from Jira</summary><type>Task</type><priority>Medium</priority>
  <status>` + status + `</status><statusCategory key="` + category + `"/>
  <created>Mon, 5 Oct 2026 10:00:00 +0200</created><updated>Mon, 5 Oct 2026 10:00:00 +0200</updated></item>`
}

func TestImportJiraKeepsLocalIssuesAndOtherProjects(t *testing.T) {
	s := newTestStore(t)
	if _, err := s.CreateProject("RU", "Russian", ""); err != nil {
		t.Fatal(err)
	}
	local := mustIssue(t, s, "RU", "made here")
	export := `<rss version="0.92"><channel>` +
		jiraItemXML("RU-1", "RU", "Готово", "done") +
		jiraItemXML("RU-2", "RU", "В работе", "indeterminate") +
		jiraItemXML("TOOLONGPROJECT-1", "TOOLONGPROJECT", "To Do", "new") +
		`</channel></rss>`
	res, err := s.ImportJira([][]jiraItem{parse(t, export)})
	if err != nil {
		t.Fatal(err)
	}
	if res.IssuesCreated != 1 || res.IssuesUpdated != 0 || len(res.Warnings) != 2 {
		t.Fatalf("result: %+v", res)
	}
	if i, _ := s.Issue(local.Key); i.Summary != "made here" {
		t.Fatalf("local issue overwritten: %+v", i)
	}
	// Names without ASCII letters are still told apart.
	p, _ := s.Project("RU")
	i, _ := s.Issue("RU-2")
	if statusName(&p, i.StatusID) != "В работе" || i.Resolved != nil {
		t.Fatalf("status of RU-2: %q, workflow %+v", statusName(&p, i.StatusID), p.Statuses)
	}
	// The imported issue is updated by the next import.
	res, _ = s.ImportJira([][]jiraItem{parse(t, export)})
	if res.IssuesUpdated != 1 {
		t.Fatalf("re-import: %+v", res)
	}
}

func TestParseJiraXMLRejectsOtherXML(t *testing.T) {
	if _, err := ParseJiraXML(strings.NewReader("not xml at all")); err == nil {
		t.Fatal("expected an error")
	}
	if _, err := ParseJiraXML(strings.NewReader(`<rss><channel><item><summary>x</summary></item></channel></rss>`)); err == nil {
		t.Fatal("expected an error for an item without key")
	}
}

func TestHTMLToMarkdown(t *testing.T) {
	cases := []struct{ in, want string }{
		{"", ""},
		{"<p>Hello <b>world</b></p>\n\n<p>Second &amp; last</p>", "Hello **world**\n\nSecond & last"},
		{"<ol>\n\t<li>one</li>\n\t<li>two\n<ul><li>nested</li></ul></li>\n</ol>", "1. one\n2. two\n  - nested"},
		{`<div class="preformatted panel"><div class="preformattedContent panelContent"><pre>a &lt; b
  indented</pre></div></div><p>after</p>`, "```\na < b\n  indented\n```\n\nafter"},
		{`<p>See <a href="https://example.com/x" class="external-link" rel="nofollow">the docs</a> and <a href="https://e.com">https://e.com</a></p>`,
			"See [the docs](https://example.com/x) and https://e.com"},
		{"<h3><a name=\"Problem\"></a>Problem</h3><p>text&nbsp;here</p><hr />", "### Problem\n\ntext here\n\n---"},
		{"<p>line<br/>\nnext</p>", "line\nnext"},
		{"<p>x <em>y</em> <tt>z</tt></p>", "x _y_ `z`"},
	}
	for _, c := range cases {
		if got := HTMLToMarkdown(c.in); got != c.want {
			t.Errorf("HTMLToMarkdown(%q)\n got: %q\nwant: %q", c.in, got, c.want)
		}
	}
}
